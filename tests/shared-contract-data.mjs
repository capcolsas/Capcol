import assert from 'node:assert/strict';
import { shareContractStream, shareContractImageUrls } from '../src/assets/js/utils/sharedContractData.js';
let scope = 'user-a';
let starts = 0, stops = 0;
const sources = [];
const shared = shareContractStream((data, error, status) => {
  starts++; sources.push({ data, error, status });
  return () => { stops++; };
}, () => scope);
const sidebar = [], detail = [];
const unSidebar = shared(rows => sidebar.push(rows));
const unDetail = shared(rows => detail.push(rows));
assert.equal(starts, 1, 'Sidebar and details use a single query/subscription');
sources[0].data([{codigo:'A'}]);
assert.deepEqual(sidebar, detail);
unDetail();
const reopened = [];
const unReopened = shared(rows => reopened.push(rows));
assert.equal(starts, 1);
assert.deepEqual(reopened, [[{codigo:'A'}]], 'Returning to details immediately reuses the loaded catalog');
sources[0].data([{codigo:'A',nombre:'Edited'}]);
assert.equal(reopened.at(-1)[0].nombre, 'Edited');
scope = 'user-b';
const secondUser = [];
const unSecond = shared(rows => secondUser.push(rows));
assert.equal(starts, 2);
assert.deepEqual(secondUser, [], 'A different session never receives the previous catalog');
unSidebar(); assert.equal(stops,0);
unReopened(); assert.equal(stops,1);
unSecond(); assert.equal(stops,2);
scope = 'error-case';
const unFirstError = shared(()=>{},()=>{});
const failedSource = sources.at(-1);
failedSource.error(new Error('offline'),'LOAD_ERROR'); failedSource.data([]);
const events = [];
const unError = shared(rows => events.push(['data',rows]), (e, status)=>events.push(['error',status]));
assert.deepEqual(events,[['error','LOAD_ERROR'],['data',[]]],'Preserve error/fallback ordering for new subscribers');
failedSource.data([{codigo:'Recovered'}]);
assert.equal(events.at(-1)[1][0].codigo,'Recovered');
unFirstError(); unError();
let signing = 0, rejectNext = false;
const images = shareContractImageUrls(async path => { signing++; if(rejectNext){rejectNext=false;throw Error('offline');} return 'signed:'+path; },()=>scope,50);
await Promise.all([images('logo-a'),images('logo-a'),images('logo-b')]);
assert.equal(signing,2,'Concurrent requests for the same image share one signing request');
await images('logo-a'); assert.equal(signing,2);
scope = 'new-user'; await images('logo-a'); assert.equal(signing,3);
await new Promise(resolve=>setTimeout(resolve,60)); await images('logo-a'); assert.equal(signing,4);
rejectNext=true; await assert.rejects(images('error-logo'),/offline/);
await images('error-logo'); assert.equal(signing,6,'A failed signature is not cached');
console.log('PASS: one contract query/subscription for sidebar + details, immediate navigation replay, live edits, cleanup, session isolation, error recovery and deduplicated expiring image URLs.');
